"""Integrity + drift checker for the labelled dataset the study runs on.

    python data/check_dataset.py            # report, exit 1 on FAIL
    python data/check_dataset.py --strict   # also exit 1 on drift warnings

Three questions, in order of how much they would embarrass a reviewer:

1. Does every resume have a label and does every label have a resume? evaluate.py raises
   on the first half only, so an orphan row in labels.csv is silent.
2. Is the shipped text internally consistent? The experience ranges generated by
   generate_dataset.py used to be able to run backwards ("2024-2023") once the role
   cursor stepped below graduation year.
3. Does the generator in this checkout still produce the resumes in this checkout? If it
   does not, results.csv was measured on text that no longer exists in the repo, and the
   tables in README cannot be reproduced from source without re-running the evaluation.
"""
import argparse
import csv
import re
import subprocess
import sys
import tempfile
from collections import Counter
from pathlib import Path

DATA = Path(__file__).resolve().parent
RESUMES = DATA / "resumes"
YEARS_RE = re.compile(r"^(.*)\(([^()]*\b)(\d{4})-(\d{4})\b([^()]*)\)\.$")
WORD_RANGE = (60, 900)      # the band the evidence budget was sized for
TRUNCATED_BELOW = 25        # under this the file is a stub, not a short CV

failures: list[str] = []
warnings: list[str] = []


def fail(msg: str) -> None:
    failures.append(msg)


def warn(msg: str) -> None:
    warnings.append(msg)


def read_labels() -> dict[str, int]:
    with (DATA / "labels.csv").open(encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh))
    out: dict[str, int] = {}
    for row in rows:
        name = (row.get("resume_id") or "").strip()
        if not name:
            continue
        try:
            score = int(float(row["human_score"]))
        except (KeyError, TypeError, ValueError):
            fail(f"labels.csv: {name!r} has no usable human_score")
            continue
        if name in out:
            fail(f"labels.csv: {name!r} appears more than once")
        out[name] = score
    return out


def check_coverage(labels: dict[str, int]) -> None:
    files = {p.name for p in RESUMES.iterdir() if p.suffix in (".txt", ".pdf", ".docx")}
    for missing in sorted(files - set(labels)):
        fail(f"no human_score for {missing}")
    for orphan in sorted(set(labels) - files):
        fail(f"labels.csv row {orphan} has no resume file")
    print(f"coverage: {len(files)} resumes, {len(labels)} labels, "
          f"{len(files & set(labels))} paired")


def check_scores(labels: dict[str, int]) -> None:
    tiers = Counter()
    for name, score in labels.items():
        if not 0 <= score <= 100:
            fail(f"{name}: label {score} outside 0-100")
        match = re.search(r"_(strong|medium|weak)\.txt$", name)
        if match:
            tiers[match.group(1)] += 1
    spread = sorted(labels.values())
    print(f"labels: min {spread[0]} / median {spread[len(spread) // 2]} / max {spread[-1]}, "
          f"distinct {len(set(spread))}, generated tiers "
          + ", ".join(f"{t}={tiers[t]}" for t in ("strong", "medium", "weak")))
    if len(set(spread)) < 10:
        warn(f"only {len(set(spread))} distinct labels - rank correlation is tie-dominated")


def check_year_ranges(name: str, text: str) -> None:
    """Experience lines look like `Experience: Title (Place, 2022-2024).`"""
    previous_start = None
    for line in text.splitlines():
        m = YEARS_RE.search(line.strip())
        if not m:
            continue
        start, end = int(m.group(3)), int(m.group(4))
        if start > end:
            fail(f"{name}: experience range runs backwards: {line.strip()}")
        if previous_start is not None and end > previous_start:
            fail(f"{name}: roles not listed most-recent-first: {line.strip()} "
                 f"follows a role that ended at {previous_start}")
        previous_start = start


def check_texts(labels: dict[str, int]) -> dict[str, str]:
    texts, seen = {}, {}
    for name in sorted(labels):
        path = RESUMES / name
        text = path.read_text(encoding="utf-8", errors="replace")
        texts[name] = text
        words = len(text.split())
        if words < TRUNCATED_BELOW:
            fail(f"{name}: {words} words, a stub rather than a resume")
        elif words < WORD_RANGE[0]:
            # Deliberate for the two hand-written CVs, but worth naming: on a document
            # this short the evidence budget returns the whole text, so RAG and
            # full-context differ only by the prompt scaffolding.
            warn(f"{name}: {words} words, below the {WORD_RANGE[0]}-word floor - "
                 "retrieval has nothing to leave out")
        elif words > WORD_RANGE[1]:
            fail(f"{name}: {words} words, outside the {WORD_RANGE} band the "
                 "evidence budget was sized for")
        if not text.startswith("Candidate"):
            warn(f"{name}: does not open with a candidate header")
        if (dup := seen.get(text)):
            fail(f"{name} is byte-identical to {dup}")
        else:
            seen[text] = name
        check_year_ranges(name, text)
    return texts


def check_generator_drift(texts: dict[str, str]) -> None:
    """Re-run the generator into a temp dir (writes nothing here) and diff the text."""
    with tempfile.TemporaryDirectory() as tmp:
        proc = subprocess.run(
            [sys.executable, str(DATA / "generate_dataset.py"), "--out", tmp],
            capture_output=True, text=True)
        if proc.returncode != 0:
            warn(f"generator did not run: {proc.stderr.strip().splitlines()[-1:]}")
            return
        regenerated = {p.name: p.read_text(encoding="utf-8")
                       for p in (Path(tmp) / "resumes").iterdir()}
    stale, kinds, moved = [], set(), 0
    for name, text in texts.items():
        fresh = regenerated.get(name)
        if fresh is None:
            continue                       # hand-written CV, not the generator's output
        if fresh != text:
            fl, tl = fresh.splitlines(), text.splitlines()
            first = next((i for i, (a, b) in enumerate(zip(fl, tl)) if a != b), 0)
            stale.append(f"{name}:{first + 1}")
            for a, b in zip(fl, tl):
                if a != b:
                    moved += 1
                    kinds.add(b.strip().split(":")[0] if ":" in b else "other")
            for extra in tl[len(fl):] + fl[len(tl):]:
                moved += 1
                kinds.add(extra.strip().split(":")[0] if ":" in extra else "other")
    if stale:
        what = " / ".join(sorted(kinds))
        warn(f"{len(stale)} generated resumes differ from the generator in this checkout: "
             f"{moved} changed lines, all of type [{what}]: {', '.join(stale)}")
        print(f"       -> the drift is confined to {what} lines; regenerate with "
              "`python data/generate_dataset.py` and re-run evaluate.py, or keep the "
              "shipped text and treat the results CSVs as measured on it")
    else:
        print("generator drift: none - the shipped resumes match this checkout's generator")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--strict", action="store_true",
                    help="treat warnings (label spread, generator drift) as failures")
    args = ap.parse_args()

    labels = read_labels()
    check_coverage(labels)
    check_scores(labels)
    texts = check_texts(labels)
    check_generator_drift(texts)

    print(f"\n{len(failures)} FAIL, {len(warnings)} WARN")
    for line in failures:
        print(f"  FAIL  {line}")
    for line in warnings:
        print(f"  WARN  {line}")
    return 1 if failures or (args.strict and warnings) else 0


if __name__ == "__main__":
    sys.exit(main())
